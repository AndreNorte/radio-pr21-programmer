import SwiftUI

/// Справка: зачем профили, как выбирать канал и мощность, что говорят нормы.
struct HelpView: View {
    @Environment(\.dismiss) private var dismiss

    private struct Article: Identifiable {
        let id = UUID()
        let title: String
        let body: String
    }

    private let articles: [Article] = [
        Article(title: "Зачем нужны профили", body: """
        У этой рации всего 16 ячеек, а в России в полосе PMR446 разрешено только восемь каналов \
        (446,00625 … 446,09375 МГц с шагом 12,5 кГц). Менять в них можно немногое: частоту в \
        пределах сетки, тон, мощность и шумоподавление.

        Профиль — это заранее собранный набор всех 16 каналов плюс уровень шумодава. Он нужен, \
        чтобы не крутить поля вручную каждый раз, когда меняются условия: приехали в лес — \
        выбрали «Лес и ЛЭП», выехали на трассу — «Трасса». Профиль действительно меняет частоты, \
        тона, мощность и скан, а не только надпись на кнопке.
        """),
        Article(title: "Как далеко слышно на 446 МГц", body: """
        PMR446 работает в УКВ-диапазоне, где связь почти как у света: нужна прямая видимость. \
        Отсюда разброс дальности при одинаковой мощности:

        • открытая местность, взаимная видимость — до 5 км;
        • городская застройка — 1–1,5 км;
        • лес — сотни метров, кроны гасят сигнал;
        • складки рельефа — решают гребни, а не мощность.

        Прибавка мощности с 0,5 до 2 Вт даёт +6 дБ, то есть выигрыш в дальности примерно вдвое — \
        и он полностью теряется за одним холмом. Поэтому порядок такой: высота и позиция, затем \
        мощность, и только потом шумодав.
        """),
        Article(title: "Мощность и норма", body: """
        В России для PMR446 решение ГКРЧ № 05-10-02-001 от 28.11.2005 ограничивает ЭИИМ \
        значением 0,5 Вт и разрешает восемь каналов с шагом 12,5 кГц. У рации низкая мощность \
        как раз 0,5 Вт, высокая — 2 Вт.

        Приложение не запрещает высокую мощность: оно показывает предупреждение, а решение \
