        4. Нажмите «Записать в рацию». Программа сама снимет бэкап, запишет и сверит результат.
        5. Выньте кабель и выключите-включите рацию, чтобы настройки применились.
        """),
    ]

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            HStack {
                Text("Справка").font(.system(size: 20, weight: .bold)).foregroundStyle(Theme.text)
                Spacer()
                Button("Закрыть") { dismiss() }.keyboardShortcut(.cancelAction)
            }
            .padding(20)

            ScrollView {
                VStack(alignment: .leading, spacing: 18) {
                    ForEach(articles) { article in
                        VStack(alignment: .leading, spacing: 6) {
                            Text(article.title)
                                .font(.system(size: 15, weight: .semibold))
                                .foregroundStyle(Theme.accent)
                            Text(article.body)
                                .font(.system(size: 13))
                                .foregroundStyle(Theme.text)
                                .fixedSize(horizontal: false, vertical: true)
                        }
                    }
                }
                .padding(.horizontal, 20)
                .padding(.bottom, 24)
            }
        }
        .frame(width: 620, height: 560)
        .background(Theme.panel)
    }
