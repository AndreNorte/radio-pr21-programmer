        Мощность здесь помогает меньше всего: она поднимает и полезный сигнал, и шум приёмника.
        """),
        Article(title: "Быстрый старт", body: """
        1. Вставьте штекеры кабеля в рацию, включите её. Она при этом не передаёт и не пищит — \
